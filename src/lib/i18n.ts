type TranslationKey = keyof typeof translations.cs;
type NormalizedLocale = "ru" | "cs" | "uk" | "en";

export function normalizeLocale(locale?: string | null): NormalizedLocale {
  const normalized = locale?.toLowerCase().split(/[-_]/)[0];
  if (normalized === "cz" || normalized === "cs") return "cs";
  if (normalized === "ru" || normalized === "uk" || normalized === "en") return normalized;
  return "cs";
}

let _currentLocale: NormalizedLocale = normalizeLocale(process.env.EXPO_PUBLIC_APP_LOCALE);

export function getLocale(): NormalizedLocale {
  return _currentLocale;
}

export function setAppLocale(locale: string) {
  _currentLocale = normalizeLocale(locale);
}

export function t(key: TranslationKey, params?: TranslationParams, locale?: AppLocale): string {
  const normalizedLocale = normalizeLocale(locale ?? _currentLocale);
  const template = String(translations[normalizedLocale][key] ?? translations.cs[key] ?? key);
  if (!params) return template;
  return Object.entries(params).reduce((text, [paramKey, value]) => text.replaceAll(`{${paramKey}}`, String(value)), template);
}

export function formatLocalizedDate(value: string | Date, options: Intl.DateTimeFormatOptions, locale?: AppLocale) {
  const date = value instanceof Date ? value : new Date(value);
  return new Intl.DateTimeFormat(toIntlLocale(locale ?? _currentLocale), options).format(date);
}

export function formatLocalizedMonth(value: Date, locale?: AppLocale) {
  return formatLocalizedDate(value, { month: "long" }, locale);
}

export function toIntlLocale(locale?: AppLocale) {
  const normalizedLocale = normalizeLocale(locale ?? _currentLocale);
  if (normalizedLocale === "cs") return "cs-CZ";
  if (normalizedLocale === "uk") return "uk-UA";
  if (normalizedLocale === "ru") return "ru-RU";
  return "en-US";
}
